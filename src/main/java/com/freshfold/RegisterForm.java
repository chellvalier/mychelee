    private void tombol_daftarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_tombol_daftarActionPerformed
        String nama = nama_lengkap.getText().trim();
        String username = txtUname.getText().trim();
        String password = String.valueOf(txtPass.getPassword());
        String konfirmasi = String.valueOf(konfirm_pass.getPassword());
        String emailUser = email.getText().trim();
        String nomorHp = no_hp.getText().trim();
        String alamatUser = alamat.getText().trim();
        
        if (nama.isEmpty() || username.isEmpty() || password.isEmpty() || konfirmasi.isEmpty() || emailUser.isEmpty() || nomorHp.isEmpty() || alamatUser.isEmpty()) {
            javax.swing.JOptionPane.showMessageDialog(
                    this, "Semua data wajib diisi!"
                    );
            return;
        }
        
        if (!password.equals(konfirmasi)) {
            javax.swing.JOptionPane.showMessageDialog(
            this, "Konfirmasi password tidak sesuai!"
            );
            return;
        }
        
        try {
            try (AnnotationConfigApplicationContext context =
                new AnnotationConfigApplicationContext(SpringConfig.class)) {
                
                PenggunaDAO dao = context.getBean(PenggunaDAO.class);
                
                if (dao.findByUsername(username) != null) {
                    JOptionPane.showMessageDialog(
                        this, "Username sudah digunakan!"
                    );
                    return;
                }
                
                Pengguna pengguna = new Pengguna (
                        nama,
                        username,
                        password,
                        emailUser,
                        nomorHp,
                        alamatUser
                );
                dao.save(pengguna);
        }
        
        int pilihan = JOptionPane.showConfirmDialog(
            this,
                "Registrasi berhasil! Apakah Anda ingin login sekarang?", 
                "Registrasi Berhasil",  
                JOptionPane.YES_NO_OPTION
        );
        
        if (pilihan == JOptionPane.YES_OPTION) {
            LoginForm login = new LoginForm();
            login.setLocationRelativeTo(null);
            login.setVisible(true);
            this.dispose();
        } else {
            nama_lengkap.setText("");
            txtUname.setText("");
            txtPass.setText("");
            konfirm_pass.setText("");
            email.setText("");
            no_hp.setText("");
            alamat.setText("");
        }        
            
        } catch (Exception e) { 
            JOptionPane.showMessageDialog(
                    this,"Registrasi gagal! Periksa kembali data Anda.\n"
                    + e.getMessage()
            );
            e.printStackTrace();
        }
    }//GEN-LAST:event_tombol_daftarActionPerformed

